 def line(self,pts,label=None,lx=None,ly=None):
  self.a.append('<polyline points="'+' '.join(f'{x},{y}' for x,y in pts)+f'" fill="none" stroke="{self.color}" stroke-width="1.6" marker-end="url(#arrow)"/>')
